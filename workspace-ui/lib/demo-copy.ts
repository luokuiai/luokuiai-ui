const monthPattern = new RegExp("\\b(?:" + monthNames.flatMap(name => [name, name.slice(0, 3)]).join("|") + ")\\b", "g");
const prefixes: [string, string][] = [
  ["Purchase status for ", "购买状态："], ["Account for ", "账户："], ["Work status for ", "在岗状态："],
  ["Admission status for ", "就诊状态："], ["Delivery status for ", "投放状态："], ["More actions for ", "更多操作："],
  ["Sort by ", "排序依据："], ["Select ", "选择："], ["Activity for ", "活动记录："],
];

export function translateDemoCopy(text: string): string {
  const value = text.trim();
  if (!/[A-Za-z$]/.test(value)) return text;
  const direct = copy.get(value);
  if (direct) return text.replace(value, direct);
  const name = value.split(" ").map(part => people.get(part));
  if (name.length === 2 && name.every(Boolean)) return name.join("·");
  const prefix = prefixes.find(([english]) => value.startsWith(english));
  if (prefix) return prefix[1] + translateDemoCopy(value.slice(prefix[0].length));
  if (value.includes(" · ")) {
    return value.split(" · ").map(part => translateDemoCopy(part)).join(" · ");
  }
  const year = value.match(/^(H[12]|Q[1-4]) (\d{4})$/);
  if (year) return year[2] + " 年" + (year[1][0] === "H" ? (year[1][1] === "1" ? "上半年" : "下半年") : "第 " + year[1][1] + " 季度");
  const quarterSurvey = value.match(/^Q([1-4]) survey$/);
  if (quarterSurvey) return "第 " + quarterSurvey[1] + " 季度调查";
  const monthFirst = value.match(/^([A-Z][a-z]+),? (\d{1,2})(?:, (\d{4}))?$/);
  const dayFirst = value.match(/^(\d{1,2}) ([A-Z][a-z]+),? (\d{4})$/);
  const month = monthFirst?.[1] ?? dayFirst?.[2];
  if (month && monthNames.some(name => name === month || name.slice(0, 3) === month)) {
    const year = monthFirst?.[3] ?? dayFirst?.[3];
    const day = monthFirst?.[2] ?? dayFirst?.[1];
    return (year ? year + " 年 " : "") + copy.get(month) + " " + Number(day) + " 日";
  }
  const dateRange = value.match(/^(\d{1,2}) ([A-Z][a-z]+)\s*[-–]\s*(\d{1,2}) ([A-Z][a-z]+)$/);
  if (dateRange && copy.has(dateRange[2]) && copy.has(dateRange[4])) {
    return copy.get(dateRange[2]) + " " + Number(dateRange[1]) + " 日至 " + copy.get(dateRange[4]) + " " + Number(dateRange[3]) + " 日";
  }
  const duration = value.match(/^([\d,.]+) (days?|hours?|minutes?)( ago)?$/i);
  if (duration) return duration[1] + (duration[2].startsWith("day") ? " 天" : duration[2].startsWith("hour") ? " 小时" : " 分钟") + (duration[3] ? "前" : "");
  const compact = value.match(/^(\d+)m (earlier|later|wake up)$/);
  if (compact) return (compact[2] === "earlier" ? "提前 " : compact[2] === "later" ? "推迟 " : "醒来 ") + compact[1] + " 分钟";
  const metric = value.match(/^([A-Za-z ]+) ([\d.]+)([%x])$/);
  if (metric && copy.has(metric[1])) return copy.get(metric[1]) + " " + metric[2] + (metric[3] === "x" ? " 倍" : "%");
  const units = value.match(/^([\d,.]+)\s*(kcal|km|h)$/);
  if (units) return units[1] + (units[2] === "kcal" ? " 千卡" : units[2] === "km" ? " 公里" : " 小时");
  const results = value.match(/^(\d+) (?:results?|records?)$/i);
  if (results) return results[1] + " 条记录";
  const more = value.match(/^Show (\d+) more$/i);
  if (more) return "展开另外 " + more[1] + " 项";
  return text.replace(monthPattern, match => copy.get(match) ?? match).replace(/\$(?=\d)/g, "¥");
}
